# Regenerates js/demo_image.js: the screenshot(s) behind the "Load demo" button, embedded as
# base64 so the demo also works when index.html is opened from file:// (no fetch of local files).
# Usage:  powershell -ExecutionPolicy Bypass -File tools\build_demo.ps1 [sample.png ...]
param([string[]]$Files = @('rtb2004_rise_c1c3_5ns.png'))
$ErrorActionPreference = 'Stop'
$root = Split-Path $PSScriptRoot -Parent
$items = foreach ($f in $Files) {
  $b64 = [Convert]::ToBase64String([IO.File]::ReadAllBytes((Join-Path $root "samples\$f")))
  "  { name: 'demo_$f', type: 'image/png', data: '$b64' }"
}
$js = "// GENERATED by tools/build_demo.ps1 - demo screenshot(s) for the `"Load demo`" button.`n" +
      "// Loaded lazily by App.loaders.loadDemo(), so it costs nothing until used.`n" +
      "App.DEMO_IMAGES = [`n" + ($items -join ",`n") + "`n];`n"
[IO.File]::WriteAllText((Join-Path $root 'js\demo_image.js'), $js, (New-Object Text.UTF8Encoding($false)))
Write-Host "Wrote js\demo_image.js ($([math]::Round($js.Length / 1024)) KB)"
